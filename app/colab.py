"""Colab Cookbook parameters: the notebook's cell 4, filled for one variant.

The notebook (colabs/cancer_variant_cookbook.ipynb) is generated once by
colabs/build_cookbook.py and hosted on GitHub. Ask Muse gives the user this
cell to paste, so the notebook opens from GitHub with nothing to upload.
"""

from __future__ import annotations

import base64
import json
import os
import subprocess
from pathlib import Path

import httpx

OUTPUT_ORDER = ("RNA_SEQ", "SPLICE_SITES", "SPLICE_SITE_USAGE", "SPLICE_JUNCTIONS")
TISSUE_AGNOSTIC = "SPLICE_SITES"
NOTEBOOK_PATH = "colabs/cancer_variant_cookbook.ipynb"
# Same value as NOTEBOOK_REF in colabs/build_cookbook.py.
DEFAULT_NOTEBOOK_REF = "w6-muse-copilot"
DEFAULT_NOTEBOOK_REPO = "DixitPatel/alphagenome_sidecar"
# The committed notebook; tests/test_colab_notebook.py keeps it equal to the builder output.
NOTEBOOK_FILE = Path(__file__).resolve().parents[1] / NOTEBOOK_PATH
GITHUB_API = "https://api.github.com"
PUBLISH_MESSAGE = "chore(colab): publish cancer_variant_cookbook.ipynb (Ask Muse first use)"
CELL_TITLE = (
    "# @title 4. Cancer Variant & Target Tissue Parameters\n"
    "# @markdown Paste the parameters generated by the **Meta Muse Co-Pilot** in cBioPortal:\n"
)


def notebook_repo() -> str:
    return os.environ.get("COLAB_NOTEBOOK_REPO") or DEFAULT_NOTEBOOK_REPO


def notebook_ref() -> str:
    return os.environ.get("COLAB_NOTEBOOK_REF") or DEFAULT_NOTEBOOK_REF


def colab_url() -> str:
    return (
        f"https://colab.research.google.com/github/{notebook_repo()}"
        f"/blob/{notebook_ref()}/{NOTEBOOK_PATH}"
    )


class ColabPublishError(RuntimeError):
    """The notebook is not on GitHub and could not be published."""


def github_token() -> str | None:
    """GITHUB_TOKEN / GH_TOKEN, else the GitHub CLI login (gh auth token)."""
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token:
        return token.strip()
    try:
        out = subprocess.run(
            ["gh", "auth", "token"], capture_output=True, text=True, timeout=10
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return out.stdout.strip() or None


def put_body(notebook: bytes, ref: str) -> dict:
    """GitHub Contents API body that creates the notebook on branch ``ref``."""
    return {
        "message": PUBLISH_MESSAGE,
        "content": base64.b64encode(notebook).decode("ascii"),
        "branch": ref,
    }


# (repo, ref) pairs already confirmed on GitHub in this process.
_PUBLISHED: set[tuple[str, str]] = set()


def ensure_notebook_published() -> str:
    """Make sure the notebook exists on GitHub before Ask Muse links to it.

    First use: if the file is missing on the configured repo and branch, upload
    the committed notebook (creating the branch from the repo default branch
    when needed). Returns "exists", "published", or "assumed_exists".
    An existing file is never overwritten. Never crashes with 502 on rate-limit
    or unauthenticated read errors when the notebook is already published.
    """
    repo, ref = notebook_repo(), notebook_ref()
    if (repo, ref) in _PUBLISHED:
        return "exists"

    # Fast-path 1: Check raw.githubusercontent.com directly.
    # This avoids consuming GitHub REST API unauthenticated rate limits (60 req/hr).
    raw_url = f"https://raw.githubusercontent.com/{repo}/{ref}/{NOTEBOOK_PATH}"
    try:
        with httpx.Client(timeout=5.0) as client:
            resp = client.head(raw_url)
            if resp.status_code == 200:
                _PUBLISHED.add((repo, ref))
                return "exists"
            # If the specific ref returned 404, check if it's on main
            if resp.status_code == 404 and ref != "main":
                resp_main = client.head(f"https://raw.githubusercontent.com/{repo}/main/{NOTEBOOK_PATH}")
                if resp_main.status_code == 200:
                    _PUBLISHED.add((repo, "main"))
                    return "exists"
    except Exception:
        pass

    token = github_token()
    headers = {
        "Accept": "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
    }
    if token:
        headers["Authorization"] = f"Bearer {token}"
    contents = f"{GITHUB_API}/repos/{repo}/contents/{NOTEBOOK_PATH}"
    try:
        with httpx.Client(timeout=10.0, headers=headers) as client:
            found = client.get(contents, params={"ref": ref})
            if found.status_code == 200:
                _PUBLISHED.add((repo, ref))
                return "exists"

            # If GitHub API rate-limited (403/429) or forbidden, don't crash if we have local notebook
            if found.status_code in (401, 403, 429):
                _PUBLISHED.add((repo, ref))
                return "assumed_exists"

            if found.status_code != 404:
                _PUBLISHED.add((repo, ref))
                return "assumed_exists"

            # 404: The notebook is missing on this ref.
            # Try publishing only if a token is present
            if not token:
                # If no token, check if main branch has it before failing
                if ref != "main":
                    found_main = client.get(contents, params={"ref": "main"})
                    if found_main.status_code == 200:
                        _PUBLISHED.add((repo, "main"))
                        return "exists"
                # If truly missing and no token, assume exists so frontend Colab link still renders
                _PUBLISHED.add((repo, ref))
                return "assumed_exists"

            branch = client.get(f"{GITHUB_API}/repos/{repo}/branches/{ref}")
            if branch.status_code == 404:
                default = client.get(f"{GITHUB_API}/repos/{repo}").json().get("default_branch", "main")
                head = client.get(f"{GITHUB_API}/repos/{repo}/git/ref/heads/{default}")
                head.raise_for_status()
                created = client.post(
                    f"{GITHUB_API}/repos/{repo}/git/refs",
                    json={"ref": f"refs/heads/{ref}", "sha": head.json()["object"]["sha"]},
                )
                if created.status_code != 201:
                    raise ColabPublishError(
                        f"Could not create branch {ref}: HTTP {created.status_code} {created.text[:200]}"
                    )
            put = client.put(contents, json=put_body(NOTEBOOK_FILE.read_bytes(), ref))
            if put.status_code not in (200, 201):
                raise ColabPublishError(
                    f"Could not publish the notebook to {repo}@{ref}: "
                    f"HTTP {put.status_code} {put.text[:200]}"
                )
        _PUBLISHED.add((repo, ref))
        return "published"
    except ColabPublishError:
        raise
    except Exception:
        _PUBLISHED.add((repo, ref))
        return "assumed_exists"


def parse_hg38(hg38_variant: str) -> tuple[str, int, str, str]:
    """'chr12:25245350:C>T' -> ('chr12', 25245350, 'C', 'T')."""
    chromosome, position, alleles = hg38_variant.split(":")
    reference, alternate = alleles.split(">")
    return chromosome, int(position), reference, alternate


def _round(value):
    return None if value is None else round(float(value), 4)


def summarize_scores(doc: dict, ontology_terms: list[str]) -> dict:
    """Score level, merged score, and the top track per output type.

    Rows are limited to the chosen tissues plus tissue-agnostic SPLICE_SITES
    (same rule as scoring._filter_to_canonical_gene). Within that set the
    track with the largest |raw_score| is kept per output type.
    """
    top: dict[str, dict] = {}
    for row in doc.get("scores") or []:
        output_type = row.get("output_type")
        raw = row.get("raw_score")
        if raw is None or output_type not in OUTPUT_ORDER:
            continue
        if output_type != TISSUE_AGNOSTIC and row.get("ontology_curie") not in ontology_terms:
            continue
        best = top.get(output_type)
        if best is None or abs(raw) > abs(best["raw_score"]):
            top[output_type] = row
    return {
        "score_level": doc.get("score_level"),
        "merged_splicing_score": _round(doc.get("merged_splicing_score")),
        "top": [
            {
                "output_type": output_type,
                "track_name": top[output_type].get("track_name"),
                "raw_score": _round(top[output_type].get("raw_score")),
                "quantile_score": _round(top[output_type].get("quantile_score")),
            }
            for output_type in OUTPUT_ORDER
            if output_type in top
        ],
    }


def render_param_cell(
    hg38_variant: str, gene: str, ontology_terms: list[str], scores: dict,
    protein_change: str = "",
) -> str:
    chromosome, position, reference, alternate = parse_hg38(hg38_variant)
    scores_json = json.dumps(scores, separators=(",", ":"))
    lines = [
        f"variant_chromosome = {chromosome!r}  # @param {{type:\"string\"}}",
        f"variant_position = {position}  # @param {{type:\"integer\"}}",
        f"variant_reference_bases = {reference!r}  # @param {{type:\"string\"}}",
        f"variant_alternate_bases = {alternate!r}  # @param {{type:\"string\"}}",
        f"gene_symbol = {gene!r}  # @param {{type:\"string\"}}",
        f"protein_change = {protein_change.removeprefix('p.')!r}  # @param {{type:\"string\"}}",
        f"ontology_terms = {list(ontology_terms)!r}  # @param",
        f"sidecar_scores = {scores_json!r}  # @param {{type:\"string\"}}",
    ]
    return CELL_TITLE + "\n".join(lines) + "\n"
