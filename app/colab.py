"""Colab Cookbook parameters: the notebook's cell 4, filled for one variant.

The notebook (colabs/cancer_variant_cookbook.ipynb) is generated once by
colabs/build_cookbook.py and hosted on GitHub. Ask Muse gives the user this
cell to paste, so the notebook opens from GitHub with nothing to upload.
"""

from __future__ import annotations

import json
import os

OUTPUT_ORDER = ("RNA_SEQ", "SPLICE_SITES", "SPLICE_SITE_USAGE", "SPLICE_JUNCTIONS")
TISSUE_AGNOSTIC = "SPLICE_SITES"
NOTEBOOK_PATH = "colabs/cancer_variant_cookbook.ipynb"
# Same value as NOTEBOOK_REF in colabs/build_cookbook.py.
DEFAULT_NOTEBOOK_REF = "w6-muse-copilot"
CELL_TITLE = (
    "# @title 4. Cancer Variant & Target Tissue Parameters\n"
    "# @markdown Paste the parameters generated by the **Meta Muse Co-Pilot** in cBioPortal:\n"
)


def colab_url() -> str:
    ref = os.environ.get("COLAB_NOTEBOOK_REF") or DEFAULT_NOTEBOOK_REF
    return (
        "https://colab.research.google.com/github/DixitPatel/alphagenome_sidecar"
        f"/blob/{ref}/{NOTEBOOK_PATH}"
    )


def parse_hg38(hg38_variant: str) -> tuple[str, int, str, str]:
    """'chr12:25245350:C>T' -> ('chr12', 25245350, 'C', 'T')."""
    chromosome, position, alleles = hg38_variant.split(":")
    reference, alternate = alleles.split(">")
    return chromosome, int(position), reference, alternate


def _round(value):
    return None if value is None else round(float(value), 4)


def summarize_scores(doc: dict, ontology_terms: list[str]) -> dict:
    """Score level, merged score, and the top track per output type.

    Rows are limited to the chosen tissues plus tissue-agnostic SPLICE_SITES
    (same rule as scoring._filter_to_canonical_gene). Within that set the
    track with the largest |raw_score| is kept per output type.
    """
    top: dict[str, dict] = {}
    for row in doc.get("scores") or []:
        output_type = row.get("output_type")
        raw = row.get("raw_score")
        if raw is None or output_type not in OUTPUT_ORDER:
            continue
        if output_type != TISSUE_AGNOSTIC and row.get("ontology_curie") not in ontology_terms:
            continue
        best = top.get(output_type)
        if best is None or abs(raw) > abs(best["raw_score"]):
            top[output_type] = row
    return {
        "score_level": doc.get("score_level"),
        "merged_splicing_score": _round(doc.get("merged_splicing_score")),
        "top": [
            {
                "output_type": output_type,
                "track_name": top[output_type].get("track_name"),
                "raw_score": _round(top[output_type].get("raw_score")),
                "quantile_score": _round(top[output_type].get("quantile_score")),
            }
            for output_type in OUTPUT_ORDER
            if output_type in top
        ],
    }


def render_param_cell(
    hg38_variant: str, gene: str, ontology_terms: list[str], scores: dict
) -> str:
    chromosome, position, reference, alternate = parse_hg38(hg38_variant)
    scores_json = json.dumps(scores, separators=(",", ":"))
    lines = [
        f"variant_chromosome = {chromosome!r}  # @param {{type:\"string\"}}",
        f"variant_position = {position}  # @param {{type:\"integer\"}}",
        f"variant_reference_bases = {reference!r}  # @param {{type:\"string\"}}",
        f"variant_alternate_bases = {alternate!r}  # @param {{type:\"string\"}}",
        f"gene_symbol = {gene!r}  # @param {{type:\"string\"}}",
        f"ontology_terms = {list(ontology_terms)!r}  # @param",
        f"sidecar_scores = {scores_json!r}  # @param {{type:\"string\"}}",
    ]
    return CELL_TITLE + "\n".join(lines) + "\n"
